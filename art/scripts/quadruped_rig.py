"""The shared quadruped base rig (asset-list.md section 2): cow, horse, sheep, pig, goat, dog, deer.

Every quadruped uses the same bone names and hierarchy, so one animation set retargets across them. Only the
bone positions change per animal: pass a `spec` to build(). Facing -Y, Z up, origin on the floor, like the meshes.

    Root
    +-- Hips
        +-- Spine
        |   +-- Chest
        |       +-- Neck1 - Neck2 - Head - Ear_L, Ear_R
        |       +-- FrontUpper_L/R - FrontLower_L/R - FrontFoot_L/R
        +-- HindUpper_L/R - HindLower_L/R - HindFoot_L/R
        +-- Tail1 - Tail2 - Tail3

A spec maps a bone name to (head, tail). Legs and ears are given once for the left side (+X, since the animal
faces -Y) and mirrored to _R by mirror(). weights() skins a part to a set of bones by distance, so each part of
a lofted mesh follows only the bones that should move it.
"""

import bpy
from mathutils import Vector

HIERARCHY = {  # bone -> parent (names for the left side; _R is generated by mirror)
    "Root": None,
    "Hips": "Root",
    "Spine": "Hips",
    "Chest": "Spine",
    "Neck1": "Chest",
    "Neck2": "Neck1",
    "Head": "Neck2",
    "Ear_L": "Head",
    "FrontUpper_L": "Chest",
    "FrontLower_L": "FrontUpper_L",
    "FrontFoot_L": "FrontLower_L",
    "HindUpper_L": "Hips",
    "HindLower_L": "HindUpper_L",
    "HindFoot_L": "HindLower_L",
    "Tail1": "Hips",
    "Tail2": "Tail1",
    "Tail3": "Tail2",
}


def mirror(spec):
    """Add the _R bones to a spec given for the _L side (x -> -x)."""
    out = dict(spec)
    for name, (head, tail) in spec.items():
        if name.endswith("_L"):
            out[name[:-2] + "_R"] = (Vector((-head[0], head[1], head[2])), Vector((-tail[0], tail[1], tail[2])))
    return out


def parent_of(name, hierarchy=None):
    h = hierarchy or HIERARCHY
    if name.endswith("_R"):
        p = h[name[:-2] + "_L"]
        return p[:-2] + "_R" if p.endswith("_L") else p
    return h[name]


def build(rig_name, spec, collection, hierarchy=None):
    """Create the armature object in collection from spec (bone -> (head, tail)); returns it.

    hierarchy maps each left or central bone to its parent (default: the quadruped's); biped_bird.py passes its own."""
    spec = mirror({k: (Vector(h), Vector(t)) for k, (h, t) in spec.items()})
    old = bpy.data.objects.get(rig_name)
    if old is not None:
        bpy.data.objects.remove(old, do_unlink=True)
    arm = bpy.data.armatures.new(rig_name)
    obj = bpy.data.objects.new(rig_name, arm)
    collection.objects.link(obj)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.mode_set(mode="EDIT")
    made = {}
    order = ["Root"] + [n for n in spec if n != "Root"]
    for name in order:
        head, tail = spec[name]
        eb = arm.edit_bones.new(name)
        eb.head, eb.tail = head, tail
        eb.roll = 0.0
        made[name] = eb
    for name, eb in made.items():
        p = parent_of(name, hierarchy)
        if p is not None:
            eb.parent = made[p]
            eb.use_connect = False
    bpy.ops.object.mode_set(mode="OBJECT")
    for b in arm.bones:
        b.use_deform = b.name != "Root"
    arm.display_type = "OCTAHEDRAL"
    return obj


def _segment_distance(p, a, b):
    ab = b - a
    t = 0.0 if ab.length_squared == 0 else max(0.0, min(1.0, (p - a).dot(ab) / ab.length_squared))
    return (p - (a + ab * t)).length


def weights(obj, arm_obj, bone_names, falloff=3.0, keep=3):
    """Skin obj to the named bones: weight ~ 1/distance^falloff to each bone segment, the nearest few kept."""
    arm = arm_obj.data
    segs = {n: (arm.bones[n].head_local.copy(), arm.bones[n].tail_local.copy()) for n in bone_names}
    groups = {n: obj.vertex_groups.get(n) or obj.vertex_groups.new(name=n) for n in bone_names}
    for v in obj.data.vertices:
        p = obj.matrix_world @ v.co
        raw = sorted(((1.0 / (_segment_distance(p, a, b) + 0.015) ** falloff, n) for n, (a, b) in segs.items()),
                     reverse=True)[:keep]
        total = sum(w for w, _ in raw)
        for w, n in raw:
            if w / total > 0.02:
                groups[n].add([v.index], w / total, "REPLACE")


def bind(mesh_obj, arm_obj):
    """Parent the skinned mesh to the armature with an Armature modifier (weights already set)."""
    mesh_obj.parent = arm_obj
    mod = mesh_obj.modifiers.new("Armature", "ARMATURE")
    mod.object = arm_obj


def set_rot(rig_obj, name, x=None, y=None, z=None):
    """Set a pose bone's Euler rotation in degrees; axes left as None are kept."""
    import math
    b = rig_obj.pose.bones[name]
    b.rotation_mode = "XYZ"
    r = list(b.rotation_euler)
    for i, v in enumerate((x, y, z)):
        if v is not None:
            r[i] = math.radians(v)
    b.rotation_euler = r


def rest_pose(rig_obj):
    for b in rig_obj.pose.bones:
        b.rotation_mode = "XYZ"
        b.rotation_euler = (0, 0, 0)
        b.location = (0, 0, 0)
        b.scale = (1, 1, 1)


def fresh_action(rig_obj, name):
    """Give the rig one new empty action called name and delete the rig's old action and any unused ones.

    The clip exporter writes every action in the file, one FBX per clip is what Unity's Model@Clip naming
    wants, so each clip script starts from a clean slate and exports just its own action. Actions that something else
    uses (another object's animation in a shared Blender file) are left alone.
    """
    rig_obj.animation_data_create()
    old = rig_obj.animation_data.action
    rig_obj.animation_data.action = None
    for a in list(bpy.data.actions):
        if a is old or a.users == 0:
            bpy.data.actions.remove(a)
    action = bpy.data.actions.new(name)
    rig_obj.animation_data.action = action
    return action
